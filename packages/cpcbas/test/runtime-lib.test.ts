import { spawnSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import {
  RUNTIME_EXTRA_ROOTS,
  RUNTIME_FORCED_FILES,
  RUNTIME_LABEL_FILES,
} from '../src/runtime/labels.gen.js';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const runtimeDir = join(repo, 'lib/runtime');

function walk(dir: string, prefix = ''): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full, `${prefix}${name}/`));
    else out.push(`${prefix}${name}`);
  }
  return out;
}

const DIRECTIVE =
  /^[ \t]*#[ \t]*(?:include|require)(?:[ \t]+once)?[ \t]*(?:\[arch:\w+\])?[ \t]*(["<])([^>"\r\n]+)[>"]/gm;

/** Names included by a runtime file; quoted includes try the file's own directory first. */
function includesOf(file: string): { name: string; resolved: string | undefined }[] {
  const text = readFileSync(join(runtimeDir, file), 'latin1');
  const out: { name: string; resolved: string | undefined }[] = [];
  for (const m of text.matchAll(DIRECTIVE)) {
    const name = (m[2] ?? '').trim();
    const dir = dirname(file);
    const local = dir === '.' ? name : `${dir}/${name}`;
    let resolved: string | undefined;
    if (m[1] === '"' && existsSync(join(runtimeDir, local))) resolved = local;
    else if (existsSync(join(runtimeDir, name))) resolved = name;
    out.push({ name, resolved });
  }
  return out;
}

const files = walk(runtimeDir);

describe('runtime library', () => {
  it('every label file exists in lib/runtime', () => {
    expect(Object.keys(RUNTIME_LABEL_FILES).length).toBeGreaterThan(100);
    const missing = Object.values(RUNTIME_LABEL_FILES).filter((f) => !files.includes(f));
    expect(missing).toEqual([]);
    expect(RUNTIME_FORCED_FILES.filter((f) => !files.includes(f))).toEqual([]);
    expect(RUNTIME_EXTRA_ROOTS.filter((f) => !files.includes(f))).toEqual([]);
  });

  it('every #include in lib/runtime resolves inside lib/runtime', () => {
    const unresolved: string[] = [];
    for (const f of files) {
      for (const inc of includesOf(f)) {
        if (inc.resolved === undefined) unresolved.push(`${f}: ${inc.name}`);
      }
    }
    expect(unresolved).toEqual([]);
  });

  it('no file in lib/runtime is unreachable from the roots', () => {
    const reached = new Set<string>();
    const queue = [
      ...Object.values(RUNTIME_LABEL_FILES),
      ...RUNTIME_FORCED_FILES,
      ...RUNTIME_EXTRA_ROOTS,
    ];
    while (queue.length > 0) {
      const f = queue.pop() as string;
      if (reached.has(f)) continue;
      reached.add(f);
      for (const inc of includesOf(f)) if (inc.resolved !== undefined) queue.push(inc.resolved);
    }
    expect(files.filter((f) => !reached.has(f))).toEqual([]);
  });

  it('generated tables are sorted and deterministic', () => {
    const labels = Object.keys(RUNTIME_LABEL_FILES);
    expect(labels).toEqual([...labels].sort());
    expect([...RUNTIME_FORCED_FILES]).toEqual([...RUNTIME_FORCED_FILES].sort());
    expect([...RUNTIME_EXTRA_ROOTS]).toEqual([...RUNTIME_EXTRA_ROOTS].sort());
    const ts = readFileSync(join(repo, 'packages/cpcbas/src/runtime/labels.gen.ts'), 'utf8');
    expect(ts.startsWith('// GENERATED by tools/import-runtime.py')).toBe(true);
    expect(ts).toContain('AGPL-3.0-or-later');
  });

  it('lib/README lists every file under lib/runtime and its origin', () => {
    const readme = readFileSync(join(repo, 'lib/README.md'), 'utf8');
    const rows = new Map<string, string>();
    for (const m of readme.matchAll(/^\| `([^`]+)` \| (cpc|zx48k) \|$/gm)) {
      rows.set(m[1] as string, m[2] as string);
    }
    expect([...rows.keys()].sort()).toEqual(files);
    expect(readme).toMatch(/Commit: `[0-9a-f]{40}`/);
    expect(readme).toContain('https://github.com/carcharo/zxbasic');
    expect(readme).toContain('MIT');
  });

  const forkCandidates = [resolve(repo, '../zxbasic'), resolve(repo, '../../../zxbasic')];
  const fork = forkCandidates.find((p) => existsSync(join(p, 'src/lib/arch/cpc/runtime')));
  // The importer also reads cpcbuild's Boriel-era lib/ (gone from cpcbuild main since the library moved to cpcbas):
  // the check runs only where such a checkout is a sibling, as tools/import-runtime.py looks for it.
  const toolchainLib = [resolve(repo, '../cpcbuild/lib'), resolve(repo, '../../../cpcbuild/lib')].find((p) => existsSync(p));
  it.skipIf(fork === undefined || toolchainLib === undefined)('the importer is reproducible', () => {
    const r = spawnSync('python3', ['tools/import-runtime.py', '--fork', fork as string, '--check'], {
      cwd: repo,
      encoding: 'utf8',
    });
    expect(r.stderr + r.stdout).toContain('ok:');
    expect(r.status).toBe(0);
  });
});
