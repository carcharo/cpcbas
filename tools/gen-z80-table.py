#!/usr/bin/env python3
"""Generate packages/cpcbas/src/asm/z80/table.gen.ts from the reference assembler's Z80SET.

Usage: python3 tools/gen-z80-table.py [--fork ../zxbasic] [--check]

Reads <fork>/src/zxbasm/z80.py (standalone: it imports only `typing`), so plain python3
is enough. Output is deterministic: rows sorted by key. --check compares instead of writing.
"""
import argparse
import importlib.util
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'packages', 'cpcbas', 'src', 'asm', 'z80', 'table.gen.ts')

# Z80N (ZX Next) forms are in Z80SET too; the reference only accepts them with --zxnext.
Z80N_MNEMONICS = {
    'LDIX', 'LDWS', 'LDIRX', 'LDDX', 'LDDRX', 'LDPIRX', 'OUTINB', 'SWAPNIB', 'MIRROR',
    'PIXELDN', 'PIXELAD', 'SETAE', 'MUL', 'TEST', 'NEXTREG',
    'BSLA', 'BSRA', 'BSRL', 'BSRF', 'BRLC',
}
Z80N_KEYS = {'PUSH NN', 'JP (C)'}
Z80N_RE = re.compile(r'^ADD (HL|DE|BC),(A|NN)$')

# Corrections to known bugs in the reference table: key -> (opcode, reason).
CORRECTIONS = {
    'LD IYH,IYH': ('FD 64', 'z80.py has the DD (IX) prefix; the undocumented LD IYH,IYH is FD 64'),
    'LD IYH,IYL': ('FD 65', 'z80.py has the DD (IX) prefix; the undocumented LD IYH,IYL is FD 65'),
}

HEADER = """// SPDX-License-Identifier: AGPL-3.0-or-later
// GENERATED by tools/gen-z80-table.py from zxbasic src/zxbasm/z80.py (Z80SET). Do not edit.
// The table is data derived from the Boriel BASIC assembler (AGPL-3.0-or-later,
// (c) 2008-2024 Jose Manuel Rodriguez de la Rosa and contributors), under the same licence
// as cpcbas (AGPL-3.0-or-later).
//
// Row: [pattern, T-states, size in bytes, opcode template, z80n]. In the template `XX`
// marks an argument byte; z80n is 1 for ZX Spectrum Next forms (not accepted by the encoder).
"""


def load(fork):
    path = os.path.join(fork, 'src', 'zxbasm', 'z80.py')
    spec = importlib.util.spec_from_file_location('z80ref', path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.Z80SET


def is_z80n(key):
    return key.split(' ')[0] in Z80N_MNEMONICS or key in Z80N_KEYS or bool(Z80N_RE.match(key))


def render(z80set):
    rows = []
    for key in sorted(z80set):
        op = z80set[key]
        opcode = CORRECTIONS[key][0] if key in CORRECTIONS else op.opcode
        rows.append("  [%s, %d, %d, %s, %d]," % (
            repr_ts(key), op.T, op.size, repr_ts(opcode), 1 if is_z80n(key) else 0))
    out = HEADER + "\nexport type Z80Row = readonly [pattern: string, t: number, size: number, opcode: string, z80n: 0 | 1];\n\n"
    out += "export const Z80_TABLE: readonly Z80Row[] = [\n" + "\n".join(rows) + "\n];\n"
    return out


def repr_ts(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--fork', default=os.path.join(HERE, '..', '..', 'zxbasic'))
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    text = render(load(a.fork))
    if a.check:
        with open(OUT, encoding='utf-8') as f:
            sys.exit(0 if f.read() == text else 1)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


if __name__ == '__main__':
    main()
