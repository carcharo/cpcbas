#!/usr/bin/env python3
"""Generate packages/cpcbas/src/lang/firmware.gen.ts from tools/firmware-names.txt.

Usage:
    python3 tools/gen-firmware.py           # write
    python3 tools/gen-firmware.py --check   # exit 1 if the generated file is out of date

Python 3, standard library only.  Line format of the text file:
    NAME &ADDR [6128]
Blank lines and lines starting with '#' are ignored.  The output keeps the text file's
order (ascending address), so it is deterministic.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = REPO / "tools" / "firmware-names.txt"
OUT = REPO / "packages" / "cpcbas" / "src" / "lang" / "firmware.gen.ts"
LINE = re.compile(r"^([A-Z][A-Z0-9_]*) &([0-9A-F]{4})( \[6128\])?$")


def render() -> str:
    entries: list[tuple[str, int, bool]] = []
    seen_names: set[str] = set()
    seen_addrs: set[int] = set()
    for n, raw in enumerate(SRC.read_text().splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        m = LINE.match(line)
        if not m:
            sys.exit(f"{SRC}:{n}: bad line: {raw!r}")
        name, addr, flag = m.group(1), int(m.group(2), 16), m.group(3) is not None
        if name in seen_names or addr in seen_addrs:
            sys.exit(f"{SRC}:{n}: duplicate name or address: {raw!r}")
        seen_names.add(name)
        seen_addrs.add(addr)
        entries.append((name, addr, flag))
    out = [
        "// GENERATED by tools/gen-firmware.py. Do not edit; edit tools/firmware-names.txt and re-run.",
        "// Source: the Amstrad firmware jumpblock (SOFT968): names and addresses only.",
        "",
        "export interface FirmwareEntry {",
        "  readonly address: number;",
        "  /** True for entries the CPC464 (firmware V1.0) does not have. */",
        "  readonly only6128: boolean;",
        "}",
        "",
        "/** Firmware entry name (upper case) to its address, in ascending address order. */",
        "export const FIRMWARE: ReadonlyMap<string, FirmwareEntry> = new Map<string, FirmwareEntry>([",
    ]
    for name, addr, flag in entries:
        out.append(f"  ['{name}', {{ address: 0x{addr:04X}, only6128: {'true' if flag else 'false'} }}],")
    out.append("]);")
    return "\n".join(out) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is out of date; run tools/gen-firmware.py")
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
