#!/usr/bin/env python3
"""Import the CPC-reachable Z80 runtime of the reference compiler into lib/.

Usage:
    python3 tools/import-runtime.py --fork ../zxbasic          # write
    python3 tools/import-runtime.py --fork ../zxbasic --check  # verify only

Python 3, standard library only.  The fork's label table is read by importing
src.arch.z80.backend.runtime.labels from the fork (read-only).

What it does
  1. Collects roots: every value of LABEL_REQUIRED_MODULES, the files the CPC
     backend forces, the files the backend adds directly (REQUIRES.add), and
     every runtime file named by #include/#require in the CPC stdlib .bas
     files and in the toolchain library (cpcbuild/lib/**/*.bas, *.asm).
  2. Resolves each name with the fork's search order for --arch cpc:
     cpc/stdlib, cpc/runtime, zx48k/stdlib, zx48k/runtime.  Only hits in a
     runtime directory are imported; stdlib hits are reported.
  3. Follows #include in every reached file (all #if branches).
  4. Copies the files byte for byte into lib/runtime/ (flat tree: the CPC
     version where one exists, else the zx48k one), regenerates the managed
     block of lib/README.md, and writes
     packages/cpcbas/src/runtime/labels.gen.ts.

--check exits 1 if a re-run would change anything (a changed fork commit
alone only prints a note).
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
LIB = REPO / "lib"
RUNTIME_OUT = LIB / "runtime"
README = LIB / "README.md"
LABELS_TS = REPO / "packages/cpcbas/src/runtime/labels.gen.ts"

BEGIN = "<!-- BEGIN import-runtime (generated by tools/import-runtime.py; do not edit) -->"
END = "<!-- END import-runtime -->"

# The CPC backend forces these (src/arch/cpc/backend/main.py REQUIRES.add) and
# the shared Z80 backend adds these directly (src/arch/z80/backend/_array.py).
FORCED = [("bootstrap.asm", "src/arch/cpc/backend/main.py: REQUIRES.add")]
DIRECT = [("iload32.asm", "src/arch/z80/backend/_array.py: REQUIRES.add")]

# Deliberate differences from the fork: rel path -> (old bytes, new bytes), or a list of such pairs (L4-ERR), each
# occurring once. The copy gets the replacements; a fix here is listed in lib/README.md "Known defects" until the fork has it.
PATCHED = {
    "mem/alloc.asm": (
        b"#ifdef __MEMORY_CHECK__\n    ld a, ERROR_OutOfMemory\n    jp z, __ERROR",
        b"#ifdef __MEMORY_CHECK__\n    ld a, 7  ; Locomotive's Memory full (L3-FIX, follow-up 50; the Spectrum's ERROR_OutOfMemory is 3)\n    jp z, __ERROR",
    ),
    "fp_calc.asm": (
        b"    ld   de, 0\n    call L33C8",
        b"    ; L3-FIX (follow-up 43): the ROM passes DE = 0 here, a write into the Spectrum ROM that is\n"
        b"    ; ignored. The CPC's lower ROM is paged out, so &0000-&0004 (the firmware's RST 0 routine)\n"
        b"    ; was zeroed by every SKIP-CONS. The constant is discarded, so write it to the top slot of\n"
        b"    ; the FP number stack instead (the stack never holds 12 numbers here).\n"
        b"    ld   de, FP_CALC_STACK_END - 5\n    call L33C8",
    ),
    "arith/div8.asm": (b"    xor l\t\t; bit 7 of A = 1 if result is negative", b"    xor e\t\t; bit 7 of A = 1 if result is negative"),
    # L4-ERR (docs/ir.md "Errors"): the ERROR_* values are Locomotive's error numbers (follow-up 21), and __ERROR hands the
    # error to the ON ERROR trap (LOCO_ERRTRAP = SYSVAR_BASE + $220, lib/loco/vars.asm) before it prints "Error n";
    # __ERROR_FATAL is the message path, entered with A = the number.
    "error.asm": [
        (
            b"ERROR_SubscriptWrong    EQU     2\nERROR_OutOfMemory       EQU     3\nERROR_OutOfScreen       EQU     4\n"
            b"ERROR_NumberTooBig      EQU     5\nERROR_InvalidArg        EQU     9\nERROR_IntOutOfRange     EQU    10\n"
            b"ERROR_NonsenseInBasic   EQU    11\n",
            b"; L4-ERR (follow-up 21): the values are Locomotive's error numbers, not the Spectrum's\n"
            b"ERROR_SubscriptWrong    EQU     9\nERROR_OutOfMemory       EQU     7\nERROR_OutOfScreen       EQU     5\n"
            b"ERROR_NumberTooBig      EQU     6\nERROR_InvalidArg        EQU     5\nERROR_IntOutOfRange     EQU     5\n"
            b"ERROR_NonsenseInBasic   EQU     2\n",
        ),
        (
            b"ERROR_InvalidColour     EQU    19\n",
            b"ERROR_InvalidColour     EQU     5\n",
        ),
        (
            b"    ld   (ERR_NR), a\n    ld   c, a           ; stash the error number (survives TXT_OUTPUT",
            b"    ld   (ERR_NR), a\n"
            b"    ld   hl, (SYSVAR_BASE + $220)   ; L4-ERR: LOCO_ERRTRAP, the ON ERROR trap (loco/error.asm), 0 = none\n"
            b"    ld   c, a\n"
            b"    ld   a, h\n"
            b"    or   l\n"
            b"    ld   a, c\n"
            b"    jr   z, __ERROR_FATAL\n"
            b"    jp   (hl)           ; the trap, with A = the error number\n"
            b"__ERROR_FATAL:         ; L4-ERR: the message path (A = the number); the trap enters it to make an error fatal\n"
            b"    ld   c, a           ; stash the error number (survives TXT_OUTPUT",
        ),
    ],
    # L4-FIX (follow-up 130): the bare block graphics 128-143 in the CPC layout (bit 0 top left, bit 1 top right, bit 2 bottom
    # left, bit 3 bottom right), where the fork numbers them as the Spectrum (bit 0 right, bit 1 left).
    "txtglyph.asm": [
        (
            b"    ; block graphics 128-143 (Spectrum numbering): top half from bits 0-1\n    ; (1 = right, 2 = left), bottom half from bits 2-3\n",
            b"    ; block graphics 128-143 (the CPC layout, CPC manual appendix III): bit 0\n"
            b"    ; top left, bit 1 top right, bit 2 bottom left, bit 3 bottom right. The top\n"
            b"    ; half of the glyph is bits 0-1, the bottom half bits 2-3 (follow-up 130).\n",
        ),
        (
            b"__CT_TQ:                    ; A = 0-3 (bit 0 right, bit 1 left) -> A = half row byte",
            b"__CT_TQ:                    ; A = 0-3 (bit 0 left, bit 1 right) -> A = half row byte",
        ),
        (b"    DEFB $00, $0F, $F0, $FF\n__CT_FILL4", b"    DEFB $00, $F0, $0F, $FF\n__CT_FILL4"),
    ],
}

DIRECTIVE = re.compile(
    r"^[ \t]*#[ \t]*(include|require)(?:[ \t]+once)?[ \t]*(?:\[arch:(\w+)\])?[ \t]*([<\"])([^>\"\r\n]+)[>\"]",
    re.MULTILINE,
)


def directives(text: str):
    """Yield (kind, arch, local_first, name) for every include/require."""
    for m in DIRECTIVE.finditer(text):
        yield m.group(1), m.group(2), m.group(3) == '"', m.group(4).strip()


class Fork:
    def __init__(self, root: Path):
        self.root = root
        base = root / "src/lib/arch"
        self.dirs = [
            ("cpc", "stdlib", base / "cpc/stdlib"),
            ("cpc", "runtime", base / "cpc/runtime"),
            ("zx48k", "stdlib", base / "zx48k/stdlib"),
            ("zx48k", "runtime", base / "zx48k/runtime"),
        ]

    def resolve(self, name: str, local_dir: Path | None = None):
        """Return (origin, kind, relative name, absolute path) or None."""
        if local_dir is not None and (local_dir / name).is_file():
            for origin, kind, d in self.dirs:
                try:
                    rel = (local_dir / name).resolve().relative_to(d.resolve())
                except ValueError:
                    continue
                return origin, kind, rel.as_posix(), (local_dir / name)
        for origin, kind, d in self.dirs:
            p = d / name
            if p.is_file():
                return origin, kind, Path(name).as_posix(), p
        return None

    def commit(self) -> str:
        out = subprocess.run(
            ["git", "-C", str(self.root), "rev-parse", "HEAD"], capture_output=True, text=True, check=True
        )
        return out.stdout.strip()

    def branch(self) -> str:
        out = subprocess.run(
            ["git", "-C", str(self.root), "rev-parse", "--abbrev-ref", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
        )
        return out.stdout.strip()


def load_labels(fork_root: Path) -> dict[str, str]:
    sys.path.insert(0, str(fork_root))
    try:
        from src.arch.z80.backend.runtime.labels import LABEL_REQUIRED_MODULES  # type: ignore
    finally:
        sys.path.pop(0)
    return dict(LABEL_REQUIRED_MODULES)


def compute(fork: Fork, toolchain_lib: Path):
    labels = load_labels(fork.root)
    reached: dict[str, tuple[str, Path]] = {}  # rel name -> (origin, abs path)
    stdlib_hits: dict[str, str] = {}  # "origin/name" -> first referrer
    extra_roots: dict[str, str] = {}  # runtime name -> reason
    problems: list[str] = []

    def visit_runtime(rel: str, origin: str, path: Path, referrer: str):
        if rel in reached:
            return
        reached[rel] = (origin, path)
        text = path.read_text(encoding="utf-8", errors="surrogateescape")
        for _kind, arch, local_first, name in directives(text):
            if arch is not None:
                problems.append(f"{referrer}: unsupported [arch:{arch}] include in {rel}")
            hit = fork.resolve(name, path.parent if local_first else None)
            if hit is None:
                problems.append(f"{rel}: include <{name}> not found")
                continue
            o, kind, r, p = hit
            if kind != "runtime":
                problems.append(f"{rel}: include <{name}> resolves into a stdlib directory")
                continue
            visit_runtime(r, o, p, rel)

    def visit_text_root(text: str, source: str, local_dir: Path | None, seen: set[str]):
        for _kind, _arch, local_first, name in directives(text):
            hit = fork.resolve(name, local_dir if local_first else None)
            if hit is None:
                continue  # toolchain-internal name (cpcbuild/...) or user file
            o, kind, r, p = hit
            if kind == "stdlib":
                key = f"{o}/{r}"
                stdlib_hits.setdefault(key, source)
                if key not in seen and r.endswith(".bas"):
                    seen.add(key)
                    visit_text_root(p.read_text(encoding="utf-8", errors="surrogateescape"), f"{o}/stdlib/{r}", p.parent, seen)
            else:
                if r not in extra_roots:
                    extra_roots[r] = source
                visit_runtime(r, o, p, source)

    # 1. label table, forced and direct roots
    base_roots: dict[str, str] = {}
    for lbl in sorted(labels):
        base_roots.setdefault(labels[lbl], "LABEL_REQUIRED_MODULES")
    for name, why in FORCED + DIRECT:
        base_roots.setdefault(name, why)
    for name in sorted(base_roots):
        hit = fork.resolve(name)
        if hit is None or hit[1] != "runtime":
            problems.append(f"root {name} ({base_roots[name]}) not found in a runtime directory")
            continue
        visit_runtime(hit[2], hit[0], hit[3], base_roots[name])

    # 2. stdlib and toolchain-library roots
    seen: set[str] = set()
    for p in sorted((fork.dirs[0][2]).glob("**/*.bas")):
        rel = p.relative_to(fork.dirs[0][2]).as_posix()
        seen.add(f"cpc/{rel}")
        visit_text_root(p.read_text(encoding="utf-8", errors="surrogateescape"), f"cpc/stdlib/{rel}", p.parent, seen)
    tl = sorted(list(toolchain_lib.glob("**/*.bas")) + list(toolchain_lib.glob("**/*.asm")))
    for p in tl:
        rel = p.relative_to(toolchain_lib).as_posix()
        visit_text_root(p.read_text(encoding="utf-8", errors="surrogateescape"), f"cpcbuild/lib/{rel}", p.parent, seen)

    # extra roots = runtime files named by stdlib/toolchain that no label/forced root reaches by itself
    base_closure: set[str] = set()

    def walk(rel: str):
        if rel in base_closure:
            return
        base_closure.add(rel)
        origin, path = reached[rel]
        for _k, _a, lf, name in directives(path.read_text(encoding="utf-8", errors="surrogateescape")):
            hit = fork.resolve(name, path.parent if lf else None)
            if hit:
                walk(hit[2])

    for name in base_roots:
        hit = fork.resolve(name)
        if hit:
            walk(hit[2])
    extras = {r: s for r, s in sorted(extra_roots.items()) if r not in base_closure}
    return labels, base_roots, reached, stdlib_hits, extras, problems


def all_runtime_files(fork: Fork) -> dict[str, str]:
    """Every runtime file in the fork (flat view: cpc wins) -> origin."""
    out: dict[str, str] = {}
    for origin, kind, d in reversed(fork.dirs):
        if kind != "runtime":
            continue
        for p in sorted(d.glob("**/*")):
            if p.is_file():
                out[p.relative_to(d).as_posix()] = origin
    return out


def ts_str(s: str) -> str:
    assert "'" not in s and "\\" not in s, s
    return "'" + s + "'"


def gen_ts(fork: Fork, labels, base_roots, extras) -> str:
    forced = [n for n, _ in FORCED]
    direct = [n for n, _ in DIRECT]
    lines = [
        "// GENERATED by tools/import-runtime.py. Do not edit; re-run the importer.",
        "// Sources (reference compiler, branch cpc-arch): src/arch/z80/backend/runtime/labels.py",
        "// (LABEL_REQUIRED_MODULES), src/arch/cpc/backend/main.py (forced files),",
        "// src/arch/z80/backend/_array.py (direct additions), and the #include/#require lines",
        "// of the CPC stdlib and the toolchain library.",
        "// Licence: AGPL-3.0-or-later (this file, as part of the compiler); the table is a",
        "// fact list derived from the Boriel BASIC compiler (AGPL-3.0-or-later).",
        "",
        "/** Runtime label to the file under lib/runtime/ that defines it. */",
        "export const RUNTIME_LABEL_FILES: Readonly<Record<string, string>> = {",
    ]
    for lbl in sorted(labels):
        lines.append(f"  {ts_str(lbl)}: {ts_str(labels[lbl])},")
    lines += [
        "};",
        "",
        "/** Files the CPC backend always links, and files the code generator adds directly. */",
        "export const RUNTIME_FORCED_FILES: readonly string[] = [",
    ]
    for n in sorted(forced + direct):
        why = dict(FORCED + DIRECT)[n]
        lines.append(f"  {ts_str(n)}, // {why}")
    lines += [
        "];",
        "",
        "/** Runtime files named by the CPC stdlib or the toolchain library (roots beyond the label table). */",
        "export const RUNTIME_EXTRA_ROOTS: readonly string[] = [",
    ]
    for n, why in extras.items():
        lines.append(f"  {ts_str(n)}, // {why}")
    lines += ["];", ""]
    return "\n".join(lines)


def gen_readme_block(fork: Fork, commit: str, branch: str, reached, all_files, stdlib_hits, extras) -> str:
    n_cpc = sum(1 for o, _ in reached.values() if o == "cpc")
    n_zx = sum(1 for o, _ in reached.values() if o == "zx48k")
    L = [
        BEGIN,
        "",
        "## Provenance",
        "",
        "- Source: <https://github.com/carcharo/zxbasic> (fork of Boriel BASIC), "
        f"branch `{branch}`.",
        f"- Commit: `{commit}`",
        "- Imported by `tools/import-runtime.py` (stdlib-only Python 3); "
        "`python3 tools/import-runtime.py --fork ../zxbasic --check` verifies the tree.",
        f"- Files imported: {len(reached)} ({n_cpc} from `cpc`, {n_zx} from `zx48k`).",
        "",
        "## Files in `runtime/`",
        "",
        "Each file is copied byte for byte. Origin `cpc` is `src/lib/arch/cpc/runtime`, "
        "origin `zx48k` is `src/lib/arch/zx48k/runtime` (used only where `cpc` has no file of that name).",
        "",
        "| File | Origin |",
        "| --- | --- |",
    ]
    for rel in sorted(reached):
        L.append(f"| `{rel}` | {reached[rel][0]} |")
    skipped = [(r, o) for r, o in sorted(all_files.items()) if r not in reached]
    L += [
        "",
        "## Not imported",
        "",
        f"{len(skipped)} runtime files of the fork are not reachable from the CPC (label table, "
        "forced files, CPC stdlib and toolchain library roots, and their includes), "
        "so they stay behind:",
        "",
    ]
    for r, o in skipped:
        L.append(f"- `{r}` ({o})")
    L += [
        "",
        "The fork's standard library (`.bas`) is not imported here; it is ported to CPC BASIC separately.",
        "Stdlib files named by `#include`/`#require` while resolving the roots: "
        + ", ".join(f"`{k}`" for k in sorted(stdlib_hits))
        + ".",
        "",
        "## Licence",
        "",
        "The fork's runtime files carry no per-file licence header, and none is added so the copies stay "
        "identical to the fork. They are MIT licensed under the library clause of the Boriel BASIC README:",
        "",
        "- `zx48k` files: Copyright (c) José Manuel Rodríguez de la Rosa and contributors.",
        "- `cpc` files: written by Barry White for the Amstrad CPC port.",
        "",
        "The licence text is in `LICENSE` (MIT). The compiler under `packages/` is AGPL-3.0-or-later; see the top-level `NOTICE`.",
        "",
        END,
    ]
    return "\n".join(L)


COMMIT_RE = re.compile(r"^- Commit: `[0-9a-f]+`$", re.MULTILINE)

README_HEAD = """# lib/

The Z80 runtime library used by the cpcbas compiler, licensed under MIT (see `LICENSE`).
Everything between the markers below is generated; edit outside them only.

"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--fork", required=True, help="path to the reference compiler checkout")
    ap.add_argument("--toolchain-lib", default=None, help="toolchain library (default: ../cpcbuild/lib beside the repo)")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    fork = Fork(Path(args.fork).resolve())
    tl = Path(args.toolchain_lib) if args.toolchain_lib else (REPO.parent / "cpcbuild" / "lib")
    if not tl.is_dir():
        # worktree layout: .worktrees/<name> sits two levels below the repo
        for cand in (REPO.parent.parent.parent / "cpcbuild" / "lib", Path(args.fork).resolve().parent / "cpcbuild" / "lib"):
            if cand.is_dir():
                tl = cand
                break
    if not tl.is_dir():
        print("error: toolchain library not found; pass --toolchain-lib", file=sys.stderr)
        return 2

    labels, base_roots, reached, stdlib_hits, extras, problems = compute(fork, tl.resolve())
    if problems:
        for p in problems:
            print("error:", p, file=sys.stderr)
        return 2
    all_files = all_runtime_files(fork)
    commit, branch = fork.commit(), fork.branch()

    expected: dict[Path, bytes] = {}
    for rel, (_o, path) in reached.items():
        data = path.read_bytes()
        if rel in PATCHED:
            pairs = PATCHED[rel]
            for old, new in [pairs] if isinstance(pairs, tuple) else pairs:
                if data.count(old) != 1:
                    print(f"error: patch for {rel} does not apply to the fork's file", file=sys.stderr)
                    return 2
                data = data.replace(old, new)
        expected[RUNTIME_OUT / rel] = data
    expected[LABELS_TS] = gen_ts(fork, labels, base_roots, extras).encode()

    block = gen_readme_block(fork, commit, branch, reached, all_files, stdlib_hits, extras)
    old = README.read_text(encoding="utf-8") if README.is_file() else None
    if old is not None and BEGIN in old and END in old:
        head, rest = old.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        readme = head + block + tail
    else:
        readme = README_HEAD + block + "\n"
    expected[README] = readme.encode()

    changed: list[str] = []
    note: list[str] = []
    for path, data in sorted(expected.items()):
        cur = path.read_bytes() if path.is_file() else None
        if cur == data:
            continue
        if path == README and cur is not None:
            a = COMMIT_RE.sub("", cur.decode())
            b = COMMIT_RE.sub("", data.decode())
            if a == b:
                note.append(f"fork commit differs: README says another commit than {commit}")
                if args.check:
                    continue
        changed.append(str(path.relative_to(REPO)))
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    stale = []
    if RUNTIME_OUT.is_dir():
        for p in sorted(RUNTIME_OUT.glob("**/*")):
            if p.is_file() and p not in expected:
                stale.append(str(p.relative_to(REPO)))
                if not args.check:
                    p.unlink()
    for n in note:
        print("note:", n)
    if args.check:
        if changed or stale:
            for c in changed:
                print("would change:", c)
            for s in stale:
                print("would remove:", s)
            return 1
        print(f"ok: {len(reached)} runtime files up to date")
        return 0
    print(f"imported {len(reached)} files; wrote {len(changed)} changed paths; removed {len(stale)} stale")
    return 0


if __name__ == "__main__":
    sys.exit(main())
