#!/usr/bin/env node
// Generates packages/cpcbas/src/opt/peephole/rules.gen.ts from rules/*.opt (L5-PEEP).
// The library reads no file at run time: the rule texts are compiled into that module.
//
//   node tools/gen-rules.mjs          write the module
//   node tools/gen-rules.mjs --check  exit 1 if the module is not what the rules give (npm test runs this)
//
// Every file is parsed with the library's own rule parser (transpiled in memory from the TypeScript
// sources, so no build is needed): a syntax error is E574, a rule that says something wrong (a
// variable that is not bound, a function that does not exist) is E575. Either stops the generation
// with the file name and the line.
//
// SPDX-License-Identifier: AGPL-3.0-or-later
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import console from 'node:console';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import process from 'node:process';
import { pathToFileURL, fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'packages/cpcbas/src/opt/peephole');
const out = join(dir, 'rules.gen.ts');

/** Transpiles the parser's files into a temporary directory and imports the rule parser. */
async function loadParser() {
  const tmp = mkdtempSync(join(tmpdir(), 'gen-rules-'));
  for (const f of ['pattern', 'expr', 'z80regs', 'rule-parser']) {
    const src = readFileSync(join(dir, `${f}.ts`), 'utf8');
    const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } });
    writeFileSync(join(tmp, `${f}.js`), js.outputText);
  }
  return import(pathToFileURL(join(tmp, 'rule-parser.js')).href);
}

/** The text of rules.gen.ts for the rule files now in rules/. Throws `{ code, message }` for a bad rule. */
export async function generate() {
  const { parseRule } = await loadParser();
  const files = readdirSync(join(dir, 'rules'))
    .filter((f) => f.endsWith('.opt'))
    .sort();
  const names = new Set();
  const entries = [];
  for (const f of files) {
    const name = f.slice(0, -'.opt'.length);
    const text = readFileSync(join(dir, 'rules', f), 'utf8');
    if (!text.includes('SPDX-License-Identifier:')) throw Object.assign(new Error(`${f}: the file has no SPDX line (docs/ir.md "The rule files")`), { code: 'E574' });
    try {
      parseRule(name, text);
    } catch (e) {
      throw Object.assign(new Error(`${f}: ${e.message}`), { code: e.code ?? 'E574' });
    }
    if (names.has(name)) throw Object.assign(new Error(`${f}: duplicated rule name`), { code: 'E575' });
    names.add(name);
    // The `;;` comment lines (the provenance header and the notes) stay in the .opt files.
    const body = text
      .split('\n')
      .filter((l) => !l.trimStart().startsWith(';;'))
      .join('\n')
      .replace(/\n{2,}/g, '\n')
      .trim();
    entries.push(`  { name: ${JSON.stringify(name)}, text: ${JSON.stringify(`${body}\n`)} },`);
  }
  return `// SPDX-License-Identifier: AGPL-3.0-or-later
// GENERATED by tools/gen-rules.mjs from rules/*.opt. Do not edit; edit the rule files and re-run.
// The rules of the peephole pass: ported from the fork (zxbasic, AGPL-3.0-or-later) and our own (numbered from 500).
// © Copyright 2008-2024 José Manuel Rodríguez de la Rosa and contributors.
// See the file CONTRIBUTORS.md of zxbasic (https://github.com/boriel-basic/zxbasic) for copyright details.
// The provenance of each rule is in the header of its file; the comment lines are not copied here.

export interface RuleSource {
  /** The file's stem: the rule's \`--opt-disable\` name. */
  readonly name: string;
  readonly text: string;
}

export const RULE_SOURCES: readonly RuleSource[] = [
${entries.join('\n')}
];
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    const text = await generate();
    if (process.argv.includes('--check')) {
      let have = '';
      try {
        have = readFileSync(out, 'utf8');
      } catch {
        /* missing */
      }
      if (have !== text) {
        console.error('rules.gen.ts is out of date: run `node tools/gen-rules.mjs`');
        process.exit(1);
      }
    } else {
      mkdirSync(dirname(out), { recursive: true });
      writeFileSync(out, text);
      console.log(`wrote ${out}`);
    }
  } catch (e) {
    console.error(`${e.code ?? 'E574'}: ${e.message}`);
    process.exit(1);
  }
}
